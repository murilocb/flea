// The zstd frame walker against hand-built frames, so no zstd binary stands behind the answer.
use super::*;
use crate::backend::testdir::TestDir;

const MAGIC: [u8; 4] = [0x28, 0xB5, 0x2F, 0xFD];
// Single segment, one byte of content size, no checksum.
const PLAIN: u8 = 0x20;
const WITH_CHECKSUM: u8 = 0x24;
// Single segment with an eight byte content size.
const WIDE: u8 = 0xE0;

// A block header: last bit, type, and size, as three little endian bytes.
fn block(last: bool, kind: u32, size: u32) -> [u8; 3] {
    let word = (size << BLOCK_SIZE_SHIFT) | (kind << BLOCK_TYPE_SHIFT) | u32::from(last);
    [word as u8, (word >> 8) as u8, (word >> 16) as u8]
}

// A one block frame holding these bytes raw, recording their count.
fn frame(descriptor: u8, content: &[u8]) -> Vec<u8> {
    let mut out = MAGIC.to_vec();
    out.push(descriptor);
    out.push(content.len() as u8);
    out.extend(block(true, BLOCK_RAW, content.len() as u32));
    out.extend(content);
    if descriptor & HAS_CHECKSUM != 0 {
        out.extend([0u8; 4]);
    }
    out
}

fn size_of(dir: &TestDir, name: &str, bytes: &[u8]) -> (u64, bool) {
    std::fs::write(dir.join(name), bytes).unwrap();
    unpacked_size(&dir.join(name))
}

#[test]
fn the_frame_header_names_its_content_size_or_nothing() {
    // Descriptor 0x60: two-byte size, single segment; 49744 + 256 answers 50000.
    assert_eq!(parse_header(&[0x28, 0xB5, 0x2F, 0xFD, 0x60, 0x50, 0xC2]).map(|h| h.content), Some(Some(50000)));
    // Descriptor 0xA0: four-byte size, single segment, answers 100000.
    assert_eq!(parse_header(&[0x28, 0xB5, 0x2F, 0xFD, 0xA0, 0xA0, 0x86, 0x01, 0x00]).map(|h| h.content), Some(Some(100000)));
    // Descriptor 0x20: one-byte size, single segment with no dictionary, answers 100.
    assert_eq!(parse_header(&[0x28, 0xB5, 0x2F, 0xFD, 0x20, 0x64]), Some(Header { len: 6, content: Some(100), checksum: false }));
    // Descriptor 0x00: no size recorded without single segment, so unknown, never zero.
    assert_eq!(parse_header(&[0x28, 0xB5, 0x2F, 0xFD, 0x00, 0x00]), Some(Header { len: 6, content: None, checksum: false }));
    assert_eq!(parse_header(&[0x28, 0xB5]), None, "a short head is unknown, not a size");
    assert_eq!(parse_header(b"not a frame at all"), None);
}

#[test]
fn b6_two_frames_sum_both_sizes() {
    let d = TestDir::new("flashzstd-two");
    let mut both = frame(PLAIN, &[1u8; 10]);
    both.extend(frame(PLAIN, &[2u8; 7]));
    assert_eq!(size_of(&d, "both.zst", &both), (17, true));
}

#[test]
fn b6_a_truncated_second_frame_is_unknown() {
    let d = TestDir::new("flashzstd-cut");
    let mut both = frame(PLAIN, &[1u8; 10]);
    let whole = both.len();
    both.extend(frame(PLAIN, &[2u8; 7]));
    assert_eq!(size_of(&d, "cut.zst", &both[..whole + 10]), (0, false), "the second frame's block runs past the file");
    assert_eq!(size_of(&d, "half.zst", &both[..whole + 3]), (0, false), "the second frame's header is cut");
}

#[test]
fn a_checksum_an_rle_block_and_a_skippable_frame_are_walked_past() {
    let d = TestDir::new("flashzstd-walk");
    let mut all = frame(WITH_CHECKSUM, &[1u8; 5]);
    // A skippable frame of three bytes between two real ones.
    all.extend([0x55, 0x2A, 0x4D, 0x18, 3, 0, 0, 0, 9, 9, 9]);
    // An RLE frame: its block header says 40 regenerated bytes and stores one.
    all.extend(MAGIC);
    all.extend([PLAIN, 40]);
    all.extend(block(true, BLOCK_RLE, 40));
    all.push(0xAA);
    assert_eq!(size_of(&d, "walk.zst", &all), (45, true));
}

#[test]
fn a_frame_without_a_recorded_size_makes_the_whole_unknown() {
    let d = TestDir::new("flashzstd-nosize");
    let mut all = frame(PLAIN, &[1u8; 5]);
    // Descriptor 0x00 records no size and carries a window byte.
    all.extend([0x28, 0xB5, 0x2F, 0xFD, 0x00, 0x00]);
    all.extend(block(true, BLOCK_RAW, 0));
    assert_eq!(size_of(&d, "nosize.zst", &all), (0, false));
}

#[test]
fn a_reserved_block_type_and_an_overflowing_sum_are_unknown() {
    let d = TestDir::new("flashzstd-hostile");
    let mut reserved = MAGIC.to_vec();
    reserved.extend([PLAIN, 4]);
    reserved.extend(block(true, 3, 4));
    assert_eq!(size_of(&d, "reserved.zst", &reserved), (0, false));
    let huge = |size: u64| {
        let mut out = MAGIC.to_vec();
        out.push(WIDE);
        out.extend(size.to_le_bytes());
        out.extend(block(true, BLOCK_RAW, 0));
        out
    };
    let mut twice = huge(1 << 63);
    twice.extend(huge(1 << 63));
    assert_eq!(size_of(&d, "overflow.zst", &twice), (0, false), "two frames of 2^63 overflow u64");
    assert_eq!(size_of(&d, "one.zst", &huge(1 << 62)), (1 << 62, true));
}

#[test]
fn a_file_of_endless_tiny_blocks_stops_at_the_header_cap() {
    let d = TestDir::new("flashzstd-endless");
    let mut all = MAGIC.to_vec();
    all.extend([PLAIN, 1]);
    let tiny = block(false, BLOCK_RLE, 1);
    for _ in 0..=MAX_BLOCK_HEADERS {
        all.extend(tiny);
        all.push(0);
    }
    all.extend(block(true, BLOCK_RAW, 0));
    assert_eq!(size_of(&d, "endless.zst", &all), (0, false));
}
